function distanceKm(lat1: number, lng1: number, lat2: number, lng2: number): number {
  const rad = Math.PI / 180, dLat = (lat2 - lat1) * rad, dLng = (lng2 - lng1) * rad;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) ** 2;
  return 6371 * 2 * Math.asin(Math.sqrt(a));
}

export function nearestCityName(latitude: number, longitude: number): string | null {
  let best: { name: string; km: number } | null = null;
  for (const [name, lat, lng] of centers) {
    const km = distanceKm(latitude, longitude, lat, lng);
    if (!best || km < best.km) best = { name, km };
  }
  return best && best.km <= 120 ? best.name : null;
}
